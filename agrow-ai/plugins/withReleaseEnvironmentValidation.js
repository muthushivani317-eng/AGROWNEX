// Local config plugins must import their runtime package directly. `expo/config-plugins`
// is an Expo-internal export and is not reliably available to the EAS plugin resolver.
const { withAppBuildGradle } = require('@expo/config-plugins');

const START = '// @generated by withReleaseEnvironmentValidation';
const END = '// @end generated withReleaseEnvironmentValidation';

const GRADLE_BLOCK = `${START}
tasks.register("validateReleaseEnvironment", Exec) {
    group = "verification"
    description = "Fails release builds with an unsafe AgrowAI public environment"
    workingDir projectRoot
    commandLine "node", "scripts/validate-release-env.js"
}

tasks.register("validateSecurityBuildEnvironment", Exec) {
    group = "verification"
    description = "Fails release builds with active loopback, mock auth, OTP bypass, or wrong Firebase configuration"
    workingDir projectRoot
    commandLine "node", "scripts/security-build-gates.js", "--prebuild"
}

tasks.configureEach { task ->
    if (task.name == "preReleaseBuild" || task.name == "bundleRelease" ||
        task.name == "preInternalTestingBuild" || task.name == "bundleInternalTesting") {
        task.dependsOn tasks.named("validateReleaseEnvironment")
        task.dependsOn tasks.named("validateSecurityBuildEnvironment")
    }
}
${END}`;

function injectReleaseValidation(contents) {
  const start = contents.indexOf(START);
  const end = contents.indexOf(END);
  let clean = contents;
  if (start >= 0 && end >= start) {
    clean = contents.slice(0, start) + contents.slice(end + END.length);
  }
  return `${clean.trimEnd()}\n\n${GRADLE_BLOCK}\n`;
}

function withReleaseEnvironmentValidation(config) {
  return withAppBuildGradle(config, (mod) => {
    if (mod.modResults.language !== 'groovy') {
      throw new Error('release_environment_validation_requires_groovy');
    }
    mod.modResults.contents = injectReleaseValidation(mod.modResults.contents);
    return mod;
  });
}

module.exports = withReleaseEnvironmentValidation;
module.exports.injectReleaseValidation = injectReleaseValidation;
module.exports.GRADLE_BLOCK = GRADLE_BLOCK;
