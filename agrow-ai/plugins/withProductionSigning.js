// Local config plugins must import their runtime package directly. `expo/config-plugins`
// is an Expo-internal export and is not reliably available to the EAS plugin resolver.
//
// This plugin exists because `expo prebuild --clean` regenerates android/app/build.gradle
// from scratch every time, discarding any hand-edited signingConfigs/buildTypes. An earlier
// hand-edited version of this file (production signingConfig + localStandalone/internalTesting/
// kvkFieldTest build types + a validateProductionSigning task) was silently wiped by a clean
// prebuild during the 2026-08 pre-release push, which is why those build variants and that
// task appeared to vanish. Routing the production signing setup through a config plugin (the
// same pattern already used by withReleaseEnvironmentValidation.js) makes it survive prebuild.
const { withAppBuildGradle } = require('@expo/config-plugins');

const START = '// @generated by withProductionSigning';
const END = '// @end generated withProductionSigning';

const GRADLE_BLOCK = `${START}
// Production signing credentials are never committed. They're read from either real
// environment variables (CI) or the machine-local, gitignored-by-default
// ~/.gradle/gradle.properties (local builds) -- never from a file inside this repo.
def releaseStoreFilePath = System.getenv("AGROWAI_RELEASE_STORE_FILE") ?: findProperty("AGROWAI_RELEASE_STORE_FILE")
def releaseStorePassword = System.getenv("AGROWAI_RELEASE_STORE_PASSWORD") ?: findProperty("AGROWAI_RELEASE_STORE_PASSWORD")
def releaseKeyAlias = System.getenv("AGROWAI_RELEASE_KEY_ALIAS") ?: findProperty("AGROWAI_RELEASE_KEY_ALIAS")
def releaseKeyPassword = System.getenv("AGROWAI_RELEASE_KEY_PASSWORD") ?: findProperty("AGROWAI_RELEASE_KEY_PASSWORD")
def releaseSigningConfigured = [
    releaseStoreFilePath,
    releaseStorePassword,
    releaseKeyAlias,
    releaseKeyPassword,
].every { value -> value != null && value.toString().trim() }

android {
    signingConfigs {
        production {
            if (releaseSigningConfigured) {
                storeFile file(releaseStoreFilePath)
                storePassword releaseStorePassword
                keyAlias releaseKeyAlias
                keyPassword releaseKeyPassword
            }
        }
    }
    buildTypes {
        release {
            // Overrides the debug-signing fallback the stock Expo template ships with.
            signingConfig signingConfigs.production
        }
    }
}

tasks.register("validateProductionSigning") {
    group = "verification"
    description = "Fails release builds unless a real production signing credential is configured"
    doLast {
        // EAS injects its managed keystore into the release build type after this
        // project is uploaded. Validate the effective Gradle configuration so both
        // EAS-managed signing and the explicit local/CI variables are supported.
        def effectiveSigning = android.buildTypes.release.signingConfig
        def configuredStore = effectiveSigning?.storeFile
        def configuredAlias = effectiveSigning?.keyAlias
        def effectiveSigningConfigured = [
            configuredStore,
            effectiveSigning?.storePassword,
            configuredAlias,
            effectiveSigning?.keyPassword,
        ].every { value -> value != null && value.toString().trim() }
        if (!effectiveSigningConfigured) {
            throw new GradleException(
                "Production signing is not configured. Use EAS-managed Android credentials or " +
                "configure AGROWAI_RELEASE_STORE_FILE, AGROWAI_RELEASE_STORE_PASSWORD, " +
                "AGROWAI_RELEASE_KEY_ALIAS, and AGROWAI_RELEASE_KEY_PASSWORD."
            )
        }
        if (!configuredStore.isFile()) {
            throw new GradleException("Production signing keystore does not exist: \${configuredStore}")
        }
        if (configuredStore.name == "debug.keystore" || configuredAlias == "androiddebugkey") {
            throw new GradleException("Android debug signing material is forbidden for release builds.")
        }
    }
}

tasks.configureEach { task ->
    if (task.name in ["preReleaseBuild", "bundleRelease", "assembleRelease"]) {
        task.dependsOn tasks.named("validateProductionSigning")
    }
}
${END}`;

function injectProductionSigning(contents) {
  const start = contents.indexOf(START);
  const end = contents.indexOf(END);
  let clean = contents;
  if (start >= 0 && end >= start) {
    clean = contents.slice(0, start) + contents.slice(end + END.length);
  }
  return `${clean.trimEnd()}\n\n${GRADLE_BLOCK}\n`;
}

function withProductionSigning(config) {
  return withAppBuildGradle(config, (mod) => {
    if (mod.modResults.language !== 'groovy') {
      throw new Error('production_signing_requires_groovy');
    }
    mod.modResults.contents = injectProductionSigning(mod.modResults.contents);
    return mod;
  });
}

module.exports = withProductionSigning;
module.exports.injectProductionSigning = injectProductionSigning;
module.exports.GRADLE_BLOCK = GRADLE_BLOCK;
